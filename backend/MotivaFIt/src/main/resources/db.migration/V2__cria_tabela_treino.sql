DROP TABLE treinos;

CREATE TABLE treinos (
                         id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         usuario_id    BIGINT       NOT NULL REFERENCES usuarios (id),
                         nome          VARCHAR(150) NOT NULL,
                         tipo          VARCHAR(20)  NOT NULL,
                         visibilidade  VARCHAR(20)  NOT NULL DEFAULT 'PRIVADO',
                         excluido_em   TIMESTAMPTZ,
                         created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
                         updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

                         CONSTRAINT ck_treinos_tipo
                             CHECK (tipo IN ('MUSCULACAO', 'AEROBICO')),
                         CONSTRAINT ck_treinos_visibilidade
                             CHECK (visibilidade IN ('PRIVADO', 'PUBLICO'))
);

CREATE INDEX idx_treinos_usuario_id ON treinos (usuario_id);
 