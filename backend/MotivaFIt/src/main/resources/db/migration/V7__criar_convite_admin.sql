CREATE TABLE convite_admin (
                               id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               convidador_id BIGINT       NOT NULL,
                               email         VARCHAR(255) NOT NULL,
                               token_hash    VARCHAR(255) NOT NULL,
                               expira_em     TIMESTAMPTZ  NOT NULL,
                               estado        VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',

                               CONSTRAINT fk_convite_admin_convidador
                                   FOREIGN KEY (convidador_id) REFERENCES usuario (id),

                               CONSTRAINT uq_convite_admin_token_hash UNIQUE (token_hash),

                               CONSTRAINT ck_convite_admin_estado
                                   CHECK (estado IN ('PENDENTE', 'ACEITO', 'EXPIRADO', 'REVOGADO'))
);

CREATE INDEX idx_convite_admin_convidador ON convite_admin (convidador_id);

CREATE INDEX idx_convite_admin_email ON convite_admin (LOWER(email));

CREATE UNIQUE INDEX uq_convite_admin_email_pendente
    ON convite_admin (LOWER(email))
    WHERE estado = 'PENDENTE';
